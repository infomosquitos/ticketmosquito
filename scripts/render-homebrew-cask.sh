#!/usr/bin/env bash
# Render the Homebrew cask for infomosquitos/homebrew-tap from a release's
# SHA256SUMS. Writes Ruby to stdout.
# Usage: render-homebrew-cask.sh <version> <SHA256SUMS>
#   version: tag or semver (e.g. v0.2.0 or 0.2.0); the cask gets it without "v".
set -euo pipefail

VERSION="${1:?usage: render-homebrew-cask.sh <version> <SHA256SUMS>}"
SUMS="${2:?usage: render-homebrew-cask.sh <version> <SHA256SUMS>}"
VERSION="${VERSION#v}"

sha_for() {
  local sha
  sha="$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$SUMS")"
  if [[ ! "$sha" =~ ^[0-9a-f]{64}$ ]]; then
    echo "render-homebrew-cask: no sha256 for $1 in $SUMS" >&2
    exit 1
  fi
  echo "$sha"
}

SHA_ARM="$(sha_for ticketmosquito-darwin-arm64)"
SHA_INTEL="$(sha_for ticketmosquito-darwin-amd64)"

cat <<EOF
# Generated by scripts/render-homebrew-cask.sh in infomosquitos/ticketmosquito.
# Do not edit by hand: the release workflow overwrites this file.
cask "ticketmosquito" do
  arch arm: "arm64", intel: "amd64"

  version "${VERSION}"
  sha256 arm:   "${SHA_ARM}",
         intel: "${SHA_INTEL}"

  url "https://github.com/infomosquitos/ticketmosquito/releases/download/v#{version}/ticketmosquito-darwin-#{arch}"
  name "TicketMosquito"
  desc "Jira issue scraper, indexer and local MCP search server"
  homepage "https://github.com/infomosquitos/ticketmosquito"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on :macos

  binary "ticketmosquito-darwin-#{arch}", target: "ticketmosquito"

  # Release binaries are not notarized; drop the quarantine flag so
  # Gatekeeper does not block the first run.
  postflight_steps do
    run "/usr/bin/xattr",
        args:           ["-d", "com.apple.quarantine", "{{staged_path}}/ticketmosquito-darwin-#{arch}"],
        writable_paths: ["{{staged_path}}"],
        must_succeed:   false
  end

  zap trash: "~/.ticketmosquito"

  caveats <<~EOS
    Next steps:

    1. Create config, database and encryption key in ~/.ticketmosquito:
         ticketmosquito init

    2. Start the server (keep it running; it listens on http://127.0.0.1:11043):
         ticketmosquito serve

    3. Install the browser extension (Homebrew cannot do this for you).
       Download it from https://github.com/infomosquitos/ticketmosquito/releases/tag/v#{version}
         Firefox: ticketmosquito-firefox-v#{version}.xpi
                  about:addons -> gear icon -> Install Add-on From File...
         Chrome:  ticketmosquito-chrome-v#{version}.zip, unzip it into a folder you keep:
                    mkdir -p ~/Applications/TicketMosquito-Chrome
                    unzip -o ~/Downloads/ticketmosquito-chrome-v#{version}.zip -d ~/Applications/TicketMosquito-Chrome
                  chrome://extensions -> Developer mode -> Load unpacked ->
                  select that folder (not the .zip)
       Details: https://github.com/infomosquitos/ticketmosquito/blob/main/docs/guides/extension-install.md

    4. Log in to Jira, open the Ticket Mosquito extension popup and click
       "Session" to send your login to the local server.

    5. Crawl a project from the popup's Projects tab, or from the terminal:
         ticketmosquito crawl "https://your-domain.atlassian.net/browse/PROJ"
         ticketmosquito crawl PROJ

    6. Optional: connect AI agents via MCP at http://127.0.0.1:11043/mcp
       https://github.com/infomosquitos/ticketmosquito/blob/main/docs/guides/configure-mcp.md

    \`brew uninstall --zap ticketmosquito\` also deletes ~/.ticketmosquito
    (catalog, config and encryption key).
  EOS
end
EOF
